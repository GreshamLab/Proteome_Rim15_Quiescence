# ── S9: SILAC isotope incorporation (label validation) ───────────────────────
# Source: three MaxQuant proteinGroups files in figure1/.
# Combines (a) prototrophic vs auxotrophic WT in H channel, (b) prototrophic
# vs auxotrophic WT in M channel, and (c) prototrophic WT vs rim15Δ.
# Columns kept: Protein IDs, Fasta headers, comparison, normalized_ratio_mean,
# normalized_ratio_rep1, normalized_ratio_rep2 (where available).
# Contaminants (CON__) and decoy hits (+) are excluded.
message("  S9   Assembling SILAC incorporation table from figure1/ MaxQuant files...")

read_mq <- function(path, sep = ",") {
  read_delim(path, delim = sep, show_col_types = FALSE,
             name_repair = "minimal") %>%
    filter(is.na(Reverse) | Reverse != "+",
           is.na(`Potential contaminant`) | `Potential contaminant` != "+",
           !grepl("^CON__", `Protein IDs`))
}

# (a) Pro-WT H channel vs Auxo-WT H channel (replicate mean + per-rep)
pro_auxo_H <- read_mq(file.path(repo_root, "figure1/proteinGroups_pro_auxo_H.csv")) %>%
  transmute(
    `Protein IDs`,
    comparison            = "ProtoWT_H_vs_AuxoWT_H",
    normalized_ratio_mean = `Ratio H/L normalized`,
    normalized_ratio_rep1 = `Ratio H/L normalized 4`,
    normalized_ratio_rep2 = `Ratio H/L normalized 5`)

# (b) Pro-WT M channel vs Auxo-WT M channel
pro_auxo_M <- read_mq(file.path(repo_root, "figure1/proteinGroups_pro_auxo_M.csv")) %>%
  transmute(
    `Protein IDs`,
    comparison            = "ProtoWT_M_vs_AuxoWT_M",
    normalized_ratio_mean = `Ratio H/L normalized`,
    normalized_ratio_rep1 = `Ratio H/L normalized 4`,
    normalized_ratio_rep2 = `Ratio H/L normalized 5`)

# (c) Pro-WT (H channel) vs rim15Δ (M channel)
pro_rim15 <- read_mq(file.path(repo_root, "figure1/proteinGroups_rim15_HM.csv")) %>%
  transmute(
    `Protein IDs`,
    comparison            = "ProtoWT_H_vs_rim15_M",
    normalized_ratio_mean = `Ratio H/M normalized`,
    normalized_ratio_rep1 = `Ratio H/M normalized 1`,
    normalized_ratio_rep2 = `Ratio H/M normalized 2`)

s9 <- bind_rows(pro_auxo_H, pro_auxo_M, pro_rim15) %>%
  arrange(comparison, `Protein IDs`)

write_csv(s9, file.path(out_dir, "Table S9.csv"))
message(sprintf("    -> %d rows written", nrow(s9)))

