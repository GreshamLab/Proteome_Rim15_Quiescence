library(tidyverse)

repo_root <- "/Users/david/Projects/Proteome_Rim15_Quiescence"
out_dir   <- file.path(repo_root, "Final_Supplemental_Tables")
dir.create(out_dir, showWarnings = FALSE)

# Helper: copy a single file with a progress message
copy_table <- function(src, table_num, description) {
  dest <- file.path(out_dir, sprintf("Table S%d.csv", table_num))
  src_full <- file.path(repo_root, src)
  if (!file.exists(src_full)) {
    message(sprintf("  MISSING source for S%d: %s", table_num, src))
    return(invisible(NULL))
  }
  file.copy(src_full, dest, overwrite = TRUE)
  message(sprintf("  S%d  %-50s <- %s", table_num, description, src))
}

message("=== Building Final_Supplemental_Tables/ ===\n")

# ── S1: All protein SILAC data, long format ─────────────────────────────────
# Source: tables/master_protein.csv (gitignored; 142 MB; regenerated by
# 01_data_preparation_qc.Rmd). Columns: Protein IDs, Gene names, Protein names,
# Fasta headers, nutrient, samplingTime, replicate, genotype, data, value.
copy_table("tables/master_protein.csv", 1,
           "All protein SILAC data, long format")

# ── S2: All phosphosite SILAC data, long format ──────────────────────────────
# Assembled by pivoting the wide-format S6 source. Keeps per-sample normalized
# ratios (rim15KO and WT channels) and discards the pre-computed WT/rim15KO
# ratio columns (those are in S6/S19). Columns: pSite, Proteins, Leading
# proteins, Gene names, Protein names, genotype, nutrient, timepoint,
# replicate, normalized_ratio.
message("  S2   Assembling long-format phosphosite table from S6 source...")
psite_wide <- read_csv(
  file.path(repo_root, "tables/supplemental/S6_normalized_phosphosite_ratios.csv"),
  show_col_types = FALSE)

id_cols <- c("Proteins", "pSite", "Leading proteins", "Protein names", "Gene names")

psite_long <- psite_wide %>%
  select(any_of(id_cols), matches("^(rim15KO|WT)_[CNP]_T")) %>%
  pivot_longer(
    cols      = matches("^(rim15KO|WT)_[CNP]_T"),
    names_to  = "sample",
    values_to = "normalized_ratio") %>%
  separate(sample,
           into = c("genotype", "nutrient", "timepoint", "replicate"),
           sep  = "_") %>%
  mutate(timepoint_h = as.integer(sub("^T0?", "", timepoint))) %>%
  select(pSite, Proteins, `Leading proteins`, `Gene names`, `Protein names`,
         genotype, nutrient, timepoint_h, replicate, normalized_ratio,
         -any_of("Fasta headers")) %>%
  arrange(pSite, genotype, nutrient, timepoint_h, replicate)

write_csv(psite_long, file.path(out_dir, "Table S2.csv"))
message(sprintf("    -> %d rows written", nrow(psite_long)))

